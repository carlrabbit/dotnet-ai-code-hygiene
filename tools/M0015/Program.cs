namespace M0015;

internal enum ChangeClass { NewOrChanged, UnchangedContextAffected, UnchangedBackground, Unknown }
internal enum EvidenceKind { Accepted, Negative, Uncertain, Unknown, Synthetic }
internal sealed record Candidate(string Id, string Project, string Path, string Symbol, int Disambiguator, string Fingerprint, ChangeClass Change, EvidenceKind History = EvidenceKind.Unknown);
internal sealed record ReviewEvidence(string CandidateId, EvidenceKind Kind, string Provenance);
internal sealed record Policy(string Name, double ChangedWeight, double BackgroundWeight, double NegativeWeight, double ExplorationFraction);
internal sealed record Pick(string CandidateId, string Reason, double Priority);
internal sealed record GateConfiguration(string Id, string Repository, string Base, string Head, string Seed, int Budget, int UnchangedCohortMaximum, int ChangedPathCount, string ChangedPathSha256, double BaseEnumerationMs = 0, double HeadEnumerationMs = 0, string? HistoryFile = null);

internal static class Program
{
    private static readonly Policy Uniform = new("uniform", 1, 1, 1, 0);
    private static readonly Policy ChangeFirst = new("change-first", 4, 0.25, 1, 0);
    private static readonly Policy HistoryAwareFallback = new("history-aware", 4, 0.5, 2, 0.2);
    private const string GridVersion = "m0015-grid-v1";
    private static readonly (double Changed, double Background, double Exploration)[] CalibrationGrid = [(2, 1, .1), (4, .5, .2), (8, .25, .2)];

    public static async Task<int> Main(string[] args)
    {
        if (args.Length == 1 && args[0] == "self-test")
        {
            RunSelfTests(); Console.WriteLine("M0015 self-test passed"); return 0;
        }
        if (args.Length == 5 && args[0] == "compare")
        {
            Compare(args[1], args[2], args[3], args[4]); return 0;
        }
        if (args.Length != 4 || args[0] != "enumerate")
        {
            Console.Error.WriteLine("Usage: dotnet M0015.dll self-test | enumerate <repository-root> <solution.sln|slnx> <git-changed-paths.txt> | compare <base.json> <head.json> <gate.json> <output.json>");
            return 2;
        }
        return await EnumerateAsync(Path.GetFullPath(args[1]), Path.GetFullPath(args[2]), Path.GetFullPath(args[3]));
    }

    private static async Task<int> EnumerateAsync(string root, string solutionPath, string changedListPath)
    {
        if (!MSBuildLocator.IsRegistered) { MSBuildLocator.RegisterDefaults(); }
        var changedPaths = File.ReadAllLines(changedListPath).Where(x => x.Length > 0).Select(NormalizePath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        using var workspace = MSBuildWorkspace.Create();
        var diagnostics = new List<string>();
        workspace.RegisterWorkspaceFailedHandler(e => diagnostics.Add(e.Diagnostic.Message));
        Solution solution = await workspace.OpenSolutionAsync(solutionPath);
        var result = new List<Candidate>();
        foreach (Project project in solution.Projects.OrderBy(p => p.FilePath, StringComparer.Ordinal))
        {
            var projectChanged = project.Documents.Any(d => d.FilePath is not null && changedPaths.Contains(NormalizePath(Path.GetRelativePath(root, d.FilePath))));
            foreach (Document document in project.Documents.OrderBy(d => d.FilePath, StringComparer.Ordinal))
            {
                if (document.FilePath is null || !EligiblePath(document.FilePath, root)) { continue; }
                string text = (await document.GetTextAsync()).ToString();
                if (string.Join("\n", text.Split('\n').Take(5)).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)) { continue; }
                SyntaxNode? syntax = await document.GetSyntaxRootAsync();
                SemanticModel? model = await document.GetSemanticModelAsync();
                if (syntax is null || model is null) { continue; }
                string relProject = project.FilePath is null ? project.Name : NormalizePath(Path.GetRelativePath(root, project.FilePath));
                string relPath = NormalizePath(Path.GetRelativePath(root, document.FilePath));
                var declarations = syntax.DescendantNodes().OfType<MemberDeclarationSyntax>()
                    .Where(n => n is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax or InterfaceDeclarationSyntax)
                    .Select(n => (Node: n, Symbol: model.GetDeclaredSymbol(n)))
                    .Where(x => x.Symbol is not null)
                    .Select(x => (x.Node, Symbol: x.Symbol!, Name: x.Symbol!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))
                    .OrderBy(x => x.Node.SpanStart).ThenBy(x => x.Name, StringComparer.Ordinal).ToArray();
                var duplicate = new Dictionary<string, int>(StringComparer.Ordinal);
                foreach (var declaration in declarations)
                {
                    int ordinal = duplicate.GetValueOrDefault(declaration.Name); duplicate[declaration.Name] = ordinal + 1;
                    string anchor = $"{relProject}\0{relPath}\0{declaration.Name}\0{ordinal}";
                    string id = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(anchor)));
                    string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(declaration.Node.ToFullString())));
                    bool fileChanged = changedPaths.Contains(relPath);
                    ChangeClass change = fileChanged ? ChangeClass.NewOrChanged : projectChanged ? ChangeClass.Unknown : ChangeClass.UnchangedBackground;
                    result.Add(new(id, relProject, relPath, declaration.Name, ordinal, fingerprint, change));
                }
            }
        }
        var output = new { schemaVersion = 1, solution = NormalizePath(Path.GetRelativePath(root, solutionPath)), candidateCount = result.Count, workspaceDiagnostics = diagnostics, candidates = result };
        Console.WriteLine(JsonSerializer.Serialize(output, JsonOptions));
        return 0;
    }

    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true, PropertyNameCaseInsensitive = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase, Converters = { new System.Text.Json.Serialization.JsonStringEnumConverter() } };
    private static string NormalizePath(string path) => path.Replace('\\', '/').TrimStart('.', '/');
    private static bool EligiblePath(string path, string root)
    {
        if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) { return false; }
        string relative = Path.GetRelativePath(root, path);
        string[] segments = relative.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        if (segments.Any(x => x is "bin" or "obj" or ".git" or ".hygiene")) { return false; }
        string file = Path.GetFileName(path);
        return !file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) && !file.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) && !file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase);
    }

    private static void Compare(string baseFile, string headFile, string gateFile, string outputFile)
    {
        var baseData = JsonSerializer.Deserialize<CandidateFile>(File.ReadAllText(baseFile), JsonOptions) ?? throw new InvalidDataException("Base candidate file is invalid.");
        var headData = JsonSerializer.Deserialize<CandidateFile>(File.ReadAllText(headFile), JsonOptions) ?? throw new InvalidDataException("Head candidate file is invalid.");
        var gate = JsonSerializer.Deserialize<GateConfiguration>(File.ReadAllText(gateFile), JsonOptions) ?? throw new InvalidDataException("Gate config is invalid.");
        var old = baseData.Candidates.ToDictionary(x => x.Id, StringComparer.Ordinal);
        string? historyJson = gate.HistoryFile is not null && File.Exists(gate.HistoryFile) ? File.ReadAllText(gate.HistoryFile) : null;
        var historyByCandidate = ReadHistory(historyJson).ToDictionary(x => x.CandidateId, x => x.Kind, StringComparer.Ordinal);
        var candidates = headData.Candidates.Select(candidate => Classify(old.GetValueOrDefault(candidate.Id), candidate with { History = historyByCandidate.GetValueOrDefault(candidate.Id, EvidenceKind.Unknown) })).ToArray();
        var changed = candidates.Where(x => x.Change == ChangeClass.NewOrChanged).ToArray();
        var unchanged = candidates.Where(x => x.Change != ChangeClass.NewOrChanged).OrderBy(x => HashOrder(gate.Seed + "\0cohort\0" + x.Id), StringComparer.Ordinal).Take(gate.UnchangedCohortMaximum).ToArray();
        var pool = changed.Concat(unchanged).ToArray();
        var labels = pool.Where(x => x.History is EvidenceKind.Accepted or EvidenceKind.Negative).Select(x => (x.Id, x.History == EvidenceKind.Negative, x.Change)).ToArray();
        var sw = System.Diagnostics.Stopwatch.StartNew();
        Policy historyAware = Calibrate(labels, out string calibrationStatus);
        double calibrationColdMs = sw.Elapsed.TotalMilliseconds;
        Policy[] policies = [Uniform, ChangeFirst, historyAware];
        policies[2] = policies[2] with { Name = "history-aware" };
        sw.Restart();
        var selected = policies.ToDictionary(p => p.Name, p => Select(pool, gate.Budget, gate.Seed, p), StringComparer.Ordinal);
        double coldMs = sw.Elapsed.TotalMilliseconds;
        sw.Restart(); foreach (Policy policy in policies) { _ = Select(pool, gate.Budget, gate.Seed, policy); }
        double warmMs = sw.Elapsed.TotalMilliseconds;
        sw.Restart(); _ = Calibrate(labels, out _);
        double calibrationWarmMs = sw.Elapsed.TotalMilliseconds;
        var sets = selected.ToDictionary(x => x.Key, x => x.Value.Select(p => p.CandidateId).ToHashSet(StringComparer.Ordinal), StringComparer.Ordinal);
        var pairRows = new Dictionary<string, object>(StringComparer.Ordinal);
        foreach ((string Left, string Right) pair in new[] { ("uniform", "change-first"), ("uniform", "history-aware"), ("change-first", "history-aware") })
        {
            int overlap = sets[pair.Left].Intersect(sets[pair.Right], StringComparer.Ordinal).Count();
            int union = sets[pair.Left].Union(sets[pair.Right], StringComparer.Ordinal).Count();
            pairRows[$"{pair.Left}/{pair.Right}"] = new { overlapCount = overlap, jaccard = union == 0 ? 1d : (double)overlap / union };
        }
        var policyRows = selected.ToDictionary(x => x.Key, x => (object)new
        {
            selected = x.Value.Select(p =>
            {
                Candidate c = candidates.Single(y => StringComparer.Ordinal.Equals(y.Id, p.CandidateId));
                return new { id = c.Id, c.Project, c.Path, c.Symbol, c.Disambiguator, change = c.Change.ToString(), c.Fingerprint, reason = p.Reason, history = c.History.ToString() };
            }).ToArray(),
            changeRelevantCount = x.Value.Count(p => candidates.Single(c => c.Id == p.CandidateId).Change == ChangeClass.NewOrChanged),
            backgroundCount = x.Value.Count(p => candidates.Single(c => c.Id == p.CandidateId).Change != ChangeClass.NewOrChanged),
            labeledAcceptedCount = x.Value.Count(p => candidates.Single(c => c.Id == p.CandidateId).History == EvidenceKind.Accepted),
            labeledNegativeCount = x.Value.Count(p => candidates.Single(c => c.Id == p.CandidateId).History == EvidenceKind.Negative),
            unknownHistorySelectedCount = x.Value.Count(p => candidates.Single(c => c.Id == p.CandidateId).History == EvidenceKind.Unknown)
        }, StringComparer.Ordinal);
        long memoryBytes = GC.GetTotalMemory(false);
        var result = new
        {
            schemaVersion = 1, gateId = gate.Id, gate.Repository, gate.Base, gate.Head, rule = "architecture.boringness.review@2", gate.Seed, gate.Budget, gate.ChangedPathCount, gate.ChangedPathSha256,
            calibration = new { status = calibrationStatus, gridVersion = GridVersion, gridSearchRan = calibrationStatus.StartsWith("calibrated:", StringComparison.Ordinal), fallback = new { changedWeight = 4, backgroundWeight = .5, explorationFraction = .2 } },
            population = new { @base = baseData.CandidateCount, head = headData.CandidateCount, newOrChanged = changed.Length, unchangedContextAffected = candidates.Count(x => x.Change == ChangeClass.UnchangedContextAffected), unchangedBackground = candidates.Count(x => x.Change == ChangeClass.UnchangedBackground), unknownImpact = candidates.Count(x => x.Change == ChangeClass.Unknown), unchangedContextOrBackground = candidates.Length - changed.Length, unchangedExplorationCohort = unchanged.Length, comparisonPool = pool.Length, eligibleBeyondPool = candidates.Length - pool.Length },
            policies = policyRows, overlap = pairRows,
            displacement = new { changeRelevantEligible = changed.Length, historyAwareChangeRelevantSelected = selected["history-aware"].Count(p => changed.Any(c => c.Id == p.CandidateId)), changeRelevantDisplacedByExploration = Math.Max(0, Math.Min(gate.Budget, changed.Length) - selected["history-aware"].Count(p => changed.Any(c => c.Id == p.CandidateId))) },
            timing = new { baseEnumerationColdMs = Math.Round(gate.BaseEnumerationMs, 3), headEnumerationColdMs = Math.Round(gate.HeadEnumerationMs, 3), selectionColdMs = Math.Round(coldMs, 3), selectionWarmMs = Math.Round(warmMs, 3), calibrationColdMs = Math.Round(calibrationColdMs, 3), calibrationWarmMs = Math.Round(calibrationWarmMs, 3), managedHeapSnapshotBytes = memoryBytes, processWorkingSetBytes = Environment.WorkingSet },
            history = new { acceptedOrNegativeLabelsAdmitted = labels.Length, unknownHeadCandidates = candidates.Count(x => x.History == EvidenceKind.Unknown) },
            workspaceDiagnostics = new { @base = baseData.WorkspaceDiagnostics.Count, head = headData.WorkspaceDiagnostics.Count }
        };
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outputFile))!);
        string serialized = JsonSerializer.Serialize(result, JsonOptions) + Environment.NewLine;
        File.WriteAllText(outputFile, serialized);
        Console.WriteLine(JsonSerializer.Serialize(result, JsonOptions));
    }

    private sealed record CandidateFile(int CandidateCount, List<string> WorkspaceDiagnostics, List<Candidate> Candidates);
    private static string HashOrder(string value) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
    internal static Candidate Classify(Candidate? prior, Candidate current)
    {
        if (prior is null || !StringComparer.Ordinal.Equals(prior.Fingerprint, current.Fingerprint)) { return current with { Change = ChangeClass.NewOrChanged }; }
        if (current.Change == ChangeClass.NewOrChanged) { return current with { Change = ChangeClass.UnchangedContextAffected }; }
        return current;
    }

    internal static IReadOnlyList<Pick> Select(IReadOnlyList<Candidate> input, int budget, string seed, Policy policy)
    {
        if (budget < 0) { throw new ArgumentOutOfRangeException(nameof(budget)); }
        int count = Math.Min(budget, input.Count);
        if (count == 0) { return []; }
        var background = input.Where(c => c.Change != ChangeClass.NewOrChanged).ToArray();
        int explorationCount = policy.ExplorationFraction > 0 ? Math.Min(count, Math.Min(background.Length, (int)Math.Ceiling(count * policy.ExplorationFraction))) : 0;
        var exploration = background.Select(c => Rank(c, seed, policy)).OrderBy(x => x.Priority).ThenBy(x => x.CandidateId, StringComparer.Ordinal).Take(explorationCount).ToArray();
        var selectedIds = exploration.Select(x => x.CandidateId).ToHashSet(StringComparer.Ordinal);
        var ranked = input.Where(c => !selectedIds.Contains(c.Id)).Select(c => Rank(c, seed, policy))
            .OrderBy(x => x.Priority).ThenBy(x => x.CandidateId, StringComparer.Ordinal).Take(count - exploration.Length).ToArray();
        return exploration.Concat(ranked).ToArray();
    }

    private static Pick Rank(Candidate c, string seed, Policy policy)
    {
        double weight = c.Change == ChangeClass.NewOrChanged ? policy.ChangedWeight : policy.BackgroundWeight;
        if (c.History == EvidenceKind.Negative) { weight *= policy.NegativeWeight; }
        if (c.History == EvidenceKind.Accepted) { weight *= .5; }
        double u = Uniform01(seed, c.Id);
        double key = -Math.Log(u) / Math.Max(weight, 1e-12);
        string reason = c.Change == ChangeClass.NewOrChanged ? "change-relevant" : c.Change == ChangeClass.Unknown ? "unknown-impact exploration" : c.History == EvidenceKind.Negative ? "prior-negative" : "exploration/background";
        return new Pick(c.Id, reason, key);
    }
    private static double Uniform01(string seed, string candidate)
    {
        byte[] hash = SHA256.HashData(Encoding.UTF8.GetBytes($"m0015-v1\0{seed}\0{candidate}"));
        ulong n = BitConverter.ToUInt64(hash, 0) >> 11;
        return (n + 0.5) / 9007199254740992d;
    }

    internal static IReadOnlyList<ReviewEvidence> ParseHistory(IEnumerable<ReviewEvidence> evidence) => evidence
        .Where(e => (e.Kind is EvidenceKind.Accepted or EvidenceKind.Negative) && e.Provenance.StartsWith("independent:", StringComparison.Ordinal))
        .GroupBy(e => e.CandidateId, StringComparer.Ordinal).Select(g => g.Last()).ToArray();

    internal static IReadOnlyList<ReviewEvidence> ReadHistory(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) { return []; }
        try
        {
            using JsonDocument document = JsonDocument.Parse(json);
            if (!document.RootElement.TryGetProperty("schemaVersion", out JsonElement version) || version.GetInt32() != 1 || !document.RootElement.TryGetProperty("entries", out JsonElement entries) || entries.ValueKind != JsonValueKind.Array) { return []; }
            var parsed = new List<ReviewEvidence>();
            foreach (JsonElement entry in entries.EnumerateArray())
            {
                if (!entry.TryGetProperty("candidateId", out JsonElement id) || !entry.TryGetProperty("kind", out JsonElement kind) || !entry.TryGetProperty("provenance", out JsonElement provenance)) { continue; }
                if (!Enum.TryParse(kind.GetString(), true, out EvidenceKind evidenceKind)) { continue; }
                parsed.Add(new(id.GetString() ?? "", evidenceKind, provenance.GetString() ?? ""));
            }
            return ParseHistory(parsed);
        }
        catch (JsonException) { return []; }
        catch (InvalidOperationException) { return []; }
        catch (FormatException) { return []; }
    }

    internal static Policy Calibrate(IReadOnlyList<(string Id, bool Negative, ChangeClass Change)> labels, out string status)
    {
        var train = labels.Where(x => StableFold(x.Id) != 0).ToArray();
        var evaluation = labels.Where(x => StableFold(x.Id) == 0).ToArray();
        if (train.Length < 4 || evaluation.Length < 2 || train.Select(x => x.Negative).Distinct().Count() < 2)
        { status = $"uncalibrated: insufficient independent labels (train={train.Length}, evaluation={evaluation.Length})"; return HistoryAwareFallback; }
        // The finite grid is versioned and fixed above; candidate ranking sees training labels only.
        var chosen = CalibrationGrid.Select((x, i) =>
            {
                var policy = new Policy("calibration", x.Changed, x.Background, 2, x.Exploration);
                var trainingCandidates = train.Select(item => new Candidate(item.Id, "fixture", item.Id, item.Id, 0, "fixture", item.Change)).ToArray();
                var selected = Select(trainingCandidates, Math.Min(5, trainingCandidates.Length), "calibration-training-v1", policy).Select(p => p.CandidateId).ToHashSet(StringComparer.Ordinal);
                int negative = train.Count(item => selected.Contains(item.Id) && item.Negative);
                return (Parameters: x, Index: i, Yield: (double)negative / Math.Max(1, selected.Count));
            })
            .OrderByDescending(x => x.Yield).ThenBy(x => x.Index).First();
        var evaluationPolicy = new Policy("calibration", chosen.Parameters.Changed, chosen.Parameters.Background, 2, chosen.Parameters.Exploration);
        var evaluationCandidates = evaluation.Select(item => new Candidate(item.Id, "fixture", item.Id, item.Id, 0, "fixture", item.Change)).ToArray();
        var heldOut = Select(evaluationCandidates, Math.Min(5, evaluationCandidates.Length), "calibration-evaluation-v1", evaluationPolicy).Select(p => p.CandidateId).ToHashSet(StringComparer.Ordinal);
        int heldOutNegatives = evaluation.Count(item => heldOut.Contains(item.Id) && item.Negative);
        status = $"calibrated:{GridVersion};train={train.Length};heldout={evaluation.Length};heldoutSelected={heldOut.Count};heldoutNegative={heldOutNegatives}";
        return new("history-aware-calibrated", chosen.Parameters.Changed, chosen.Parameters.Background, 2, chosen.Parameters.Exploration);
    }

    private static int StableFold(string id) => SHA256.HashData(Encoding.UTF8.GetBytes(id))[0] % 2;
    private static void Assert(bool condition, string message) { if (!condition) { throw new InvalidOperationException(message); } }
    private static void RunSelfTests()
    {
        var cs = new Candidate("c", "p", "a.cs", "T", 0, "f", ChangeClass.NewOrChanged);
        var bg = new Candidate("b", "p", "b.cs", "U", 0, "g", ChangeClass.UnchangedBackground);
        Assert(Classify(null, bg).Change == ChangeClass.NewOrChanged, "new candidate invalidation");
        Assert(Classify(bg, bg with { Fingerprint = "changed" }).Change == ChangeClass.NewOrChanged, "fingerprint invalidation");
        Assert(Classify(bg, bg with { Change = ChangeClass.NewOrChanged }).Change == ChangeClass.UnchangedContextAffected, "unchanged declaration in changed file attribution");
        Assert(Classify(bg, bg with { Change = ChangeClass.Unknown }).Change == ChangeClass.Unknown, "unknown impact remains unknown");
        Assert(Select([cs, bg], 0, "s", ChangeFirst).Count == 0, "zero budget");
        Assert(Select([cs], 5, "s", ChangeFirst).Count == 1, "oversized budget");
        Assert(Select([cs, bg], 2, "s", ChangeFirst).Select(x => x.CandidateId).SequenceEqual(Select([cs, bg], 2, "s", ChangeFirst).Select(x => x.CandidateId)), "repeatability");
        Assert(Select([cs, bg], 2, "s", ChangeFirst).Select(x => x.CandidateId).Distinct().Count() == 2, "without replacement");
        int changedWins = Enumerable.Range(0, 100).Count(i => Select([cs, bg], 1, $"seed-{i}", ChangeFirst).Single().CandidateId == "c");
        Assert(changedWins >= 70, "changed candidates dominate in seeded trials");
        Assert(Select([bg], 1, "s", ChangeFirst).Single().CandidateId == "b", "unchanged eligibility/exploration");
        var history = ParseHistory([new("a", EvidenceKind.Accepted, "independent:reviewer"), new("b", EvidenceKind.Negative, "independent:reviewer"), new("c", EvidenceKind.Synthetic, "synthetic"), new("d", EvidenceKind.Accepted, "aggregate-event"), new("e", EvidenceKind.Uncertain, "independent:reviewer")]);
        Assert(history.Count == 2 && history.All(x => x.CandidateId is "a" or "b"), "history provenance filter");
        Assert(ReadHistory(null).Count == 0 && ReadHistory("{").Count == 0 && ReadHistory("{\"schemaVersion\":2,\"entries\":[]}").Count == 0, "missing/corrupt/unsupported history is unknown");
        Assert(ReadHistory("{\"schemaVersion\":1,\"entries\":[{\"candidateId\":\"x\",\"kind\":\"Accepted\",\"provenance\":\"aggregate-event\"}]}").Count == 0, "aggregate event is not a type quality label");
        Assert(ReadHistory("{\"schemaVersion\":1,\"entries\":[{\"candidateId\":\"x\",\"kind\":\"Negative\",\"provenance\":\"independent:reviewer\"}]}").Single().Kind == EvidenceKind.Negative, "independently attributable history JSON is admitted");
        var withLabels = Enumerable.Range(0, 40).Select(i => ($"label-{i}", i % 3 == 0, i % 2 == 0 ? ChangeClass.NewOrChanged : ChangeClass.UnchangedBackground)).ToArray();
        var calibrated = Calibrate(withLabels, out string calibration);
        Assert(calibration.StartsWith("calibrated:") && calibrated.Name == "history-aware-calibrated", "independent split calibration fixture");
        Assert(Calibrate(Array.Empty<(string Id, bool Negative, ChangeClass Change)>(), out string fallback).Name == "history-aware" && fallback.StartsWith("uncalibrated:"), "stable fallback");
        Assert(Calibrate([("a", true, ChangeClass.NewOrChanged)], out _).ChangedWeight == HistoryAwareFallback.ChangedWeight, "sparse fallback");
        // History changes only candidates with a separately attributable, independently recorded negative label.
        var reviewedNegative = bg with { History = EvidenceKind.Negative };
        Assert(Select([bg with { History = EvidenceKind.Accepted }, reviewedNegative], 1, "history-seed", HistoryAwareFallback).Single().CandidateId == "b", "negative evidence influences order");
        Assert(Select([bg with { History = EvidenceKind.Unknown }], 1, "history-seed", HistoryAwareFallback).Count == 1, "unknown history remains selectable");
        Assert(CalibrationGrid.Length == 3 && GridVersion == "m0015-grid-v1", "frozen finite calibration grid");
    }
}
