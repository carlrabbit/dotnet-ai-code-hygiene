    [Test]
    public async Task NewRulesDiscoverTheirFixedSourceBackedPopulations()
    {
        string repository = Path.Combine(Path.GetTempPath(), "hygiene-m0017-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(repository);
        try
        {
            await File.WriteAllTextAsync(Path.Combine(repository, "Fixture.csproj"), "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net11.0</TargetFramework></PropertyGroup></Project>");
            await File.WriteAllTextAsync(Path.Combine(repository, "Fixture.cs"), Source);
            await File.WriteAllTextAsync(Path.Combine(repository, "Generated.g.cs"), "// <auto-generated/>\n// generated comment\npublic class GeneratedFixture { }");
            RunGit(repository, "init", "-q");
            RunGit(repository, "config", "user.email", "m0017-test@example.invalid");
            RunGit(repository, "config", "user.name", "M0017 Test");
            var engine = new HygieneEngine(repository);
            _ = engine.Bootstrap();
            RunGit(repository, "add", ".");
            RunGit(repository, "commit", "-m", "fixture");
            CheckResult result = engine.Check([], false, reviewAll: true);
            Finding candidate = result.Findings.Single(finding => finding.RuleId == ControlFlowVisualBlockRuleModule.RuleId);
            await Assert.That(candidate.RuleVersion).IsEqualTo(2);
            await Assert.That(candidate.Classification).IsEqualTo("review-candidate");
            await Assert.That(candidate.Message).Contains("Review whether");
            await Assert.That(candidate.Suggestion).Contains("leave it unchanged");
            ReviewBatch types = result.ReviewBatches.Single(batch => batch.RuleId == TypeResponsibilityReviewRuleModule.RuleId);
            ReviewBatch tests = result.ReviewBatches.Single(batch => batch.RuleId == TestQualityReviewRuleModule.RuleId);
            ReviewBatch comments = result.ReviewBatches.Single(batch => batch.RuleId == CommentIntentReviewRuleModule.RuleId);
            await Assert.That(types.PopulationCount).IsEqualTo(17);
            await Assert.That(types.Items.All(item => item.Summary == "")).IsTrue();
            ReviewBatch expandedTypes = engine.ExpandReview(types.Id);
            await Assert.That(expandedTypes.Items.Any(item => item.Symbol.Contains("Nested", StringComparison.Ordinal))).IsTrue();
            await Assert.That(expandedTypes.Items.Where(item => item.Symbol.EndsWith("Sample", StringComparison.Ordinal)).Count()).IsEqualTo(2);
            await Assert.That(tests.PopulationCount).IsEqualTo(8);
            await Assert.That(tests.Items.All(item => item.Summary == "")).IsTrue();
            await Assert.That(comments.PopulationCount).IsEqualTo(5);
            await Assert.That(comments.Items.All(item => item.Line > 1 && item.Declaration.Length > 0)).IsTrue();
            string[] stableTypeIds = GetPopulation(repository, new TypeResponsibilityReviewRuleModule()).Select(subject => subject.Identity).ToArray();
            string[] stableCommentIds = GetPopulation(repository, new CommentIntentReviewRuleModule()).Select(subject => subject.Identity).ToArray();
            string[] stableTestIds = GetPopulation(repository, new TestQualityReviewRuleModule()).Select(subject => subject.Identity).ToArray();
            await Assert.That(result.ReviewBatches.Select(batch => batch.RuleId).ToArray()).IsEquivalentTo(new[]
            {
                SummaryQualityReviewRuleModule.RuleId, SummaryGermanReviewRuleModule.RuleId, BoringnessReviewRuleModule.RuleId,
                TypeResponsibilityReviewRuleModule.RuleId, TestQualityReviewRuleModule.RuleId, CommentIntentReviewRuleModule.RuleId
            });
            await Assert.That(TestQualityReviewRuleModule.RuleQuestions.Select(question => question.Id).ToArray()).IsEquivalentTo(new[] { "Q1", "Q2", "Q3" });
            await Assert.That(CommentIntentReviewRuleModule.RuleQuestions.Select(question => question.Id).ToArray()).IsEquivalentTo(new[] { "Q1", "Q2", "Q3" });
            _ = engine.AcceptReview(types.Handle, [types.Items[0].Id]);
            _ = engine.AcceptReview(tests.Handle, [tests.Items[0].Id]);
            _ = engine.AcceptReview(comments.Handle, [comments.Items[0].Id]);
            CheckResult repeated = engine.Check([], false, reviewAll: true);
            await Assert.That(repeated.ReviewBatches.Single(batch => batch.RuleId == TypeResponsibilityReviewRuleModule.RuleId).SampleCount).IsEqualTo(types.SampleCount - 1);
            await Assert.That(repeated.ReviewBatches.Single(batch => batch.RuleId == TestQualityReviewRuleModule.RuleId).SampleCount).IsEqualTo(tests.SampleCount - 1);
            await Assert.That(repeated.ReviewBatches.Single(batch => batch.RuleId == CommentIntentReviewRuleModule.RuleId).SampleCount).IsEqualTo(comments.SampleCount - 1);
            string fixturePath = Path.Combine(repository, "Fixture.cs");
            await File.WriteAllTextAsync(fixturePath, "public class UnrelatedLeading { }\n" + Source);
            await Assert.That(GetPopulation(repository, new TypeResponsibilityReviewRuleModule()).Select(subject => subject.Identity).Where(stableTypeIds.Contains).ToArray()).IsEquivalentTo(stableTypeIds);
            await Assert.That(GetPopulation(repository, new CommentIntentReviewRuleModule()).Select(subject => subject.Identity).Where(stableCommentIds.Contains).ToArray()).IsEquivalentTo(stableCommentIds);
            await Assert.That(GetPopulation(repository, new TestQualityReviewRuleModule()).Select(subject => subject.Identity).Where(stableTestIds.Contains).ToArray()).IsEquivalentTo(stableTestIds);
            string decisionsPath = Path.Combine(repository, ".hygiene", "decisions.json");
            var legacy = new
            {
                schemaVersion = 1,
                decisions = new[]
                {
                    new { id = "I-M0016", ruleId = candidate.RuleId, ruleVersion = 1, path = candidate.Path, anchor = candidate.Anchor,
                        fingerprint = candidate.Fingerprint, reason = "legacy v1 decision", createdAt = DateTimeOffset.UtcNow, discriminator = candidate.Discriminator }
                }
            };
            await File.WriteAllTextAsync(decisionsPath, JsonSerializer.Serialize(legacy));
            CheckResult afterLegacyDecision = engine.Check([], false);
            await Assert.That(afterLegacyDecision.Findings.Any(finding => finding.RuleId == candidate.RuleId)).IsTrue();
            IgnoreDecision currentIgnore = engine.Ignore(afterLegacyDecision.Findings.Single(finding => finding.RuleId == candidate.RuleId).Id, "Current v2 decision");
            await Assert.That(engine.Check([], false).Findings.Any(finding => finding.RuleId == candidate.RuleId)).IsFalse();
            engine.Unignore(currentIgnore.Id);
            await Assert.That(engine.Check([], false).Findings.Any(finding => finding.RuleId == candidate.RuleId)).IsTrue();
        }
        finally
        {
            foreach (string file in Directory.EnumerateFiles(repository, "*", SearchOption.AllDirectories)) { File.SetAttributes(file, FileAttributes.Normal); }
            Directory.Delete(repository, recursive: true);
        }
    }

    private static void RunGit(string repository, params string[] arguments)
    {
        var start = new ProcessStartInfo("git") { WorkingDirectory = repository, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
        foreach (string argument in arguments) { start.ArgumentList.Add(argument); }
        using Process process = Process.Start(start) ?? throw new InvalidOperationException("Unable to start Git fixture process.");
        string error = process.StandardError.ReadToEnd();
        process.WaitForExit();
        if (process.ExitCode != 0) { throw new InvalidOperationException("Git fixture setup failed: " + error); }
    }

    private static IReadOnlyList<ReviewSubject> GetPopulation(string repository, ISemanticReviewRuleModule module)
    {
        using var session = new RepositorySession(repository);
        Document[] documents = session.Projects.SelectMany(project => project.Documents).ToArray();
        return module.Evaluate(new RuleContext(session, documents)).ReviewSubjects;
    }

    [Test]
    public async Task VisualBlockIsVersionedAsAReviewCandidateWithoutRewriteCapability()
    {
        Rule rule = new ControlFlowVisualBlockRuleModule().Descriptor;
        await Assert.That(rule.Version).IsEqualTo(2);
        await Assert.That(rule.Classification).IsEqualTo("review-candidate");
        IRuleModule visualBlock = new ControlFlowVisualBlockRuleModule();
        await Assert.That(visualBlock is IFormatRemediationRule).IsFalse();
        await Assert.That(visualBlock is INormalizeRemediationRule).IsFalse();
    }

