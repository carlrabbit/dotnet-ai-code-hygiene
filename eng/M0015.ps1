param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('test', 'replay', 'integrity')]
    [string]$Action,
    [string]$SecondRepositoryPath,
    [string]$EvidenceRoot
)

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Set-Location $repoRoot
$project = Join-Path $repoRoot 'tools/M0015/M0015.csproj'
$configuration = Join-Path $repoRoot 'tools/M0015/Gates.json'
$toolDll = Join-Path $repoRoot 'tools/M0015/bin/Release/net11.0/M0015.dll'

function Invoke-Checked([string]$File, [string[]]$Arguments, [string]$Description) {
    & $File @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$Description failed with exit code $LASTEXITCODE." }
}

dotnet build $project --configuration Release
if ($LASTEXITCODE -ne 0) { throw "M0015 tool build failed with exit code $LASTEXITCODE." }

if ($Action -eq 'test') {
    Invoke-Checked 'dotnet' @($toolDll, 'self-test') 'M0015 selector/history/calibration fixtures'
    $fixture = Join-Path $repoRoot 'tools/M0015/fixtures'
    $changed = Join-Path $env:TEMP 'M0015-fixture-changed-paths.txt'
    [IO.File]::WriteAllText($changed, "Types.cs`n")
    $output = & dotnet $toolDll enumerate $fixture (Join-Path $fixture 'Fixture.slnx') $changed
    if ($LASTEXITCODE -ne 0) { throw "M0015 Roslyn fixture failed with exit code $LASTEXITCODE." }
    $enumeration = $output | ConvertFrom-Json
    $symbols = @($enumeration.candidates | ForEach-Object symbol)
    if ($enumeration.candidateCount -ne 6) { throw "Expected six eligible declarations (including two partial declarations); found $($enumeration.candidateCount)." }
    if (($symbols -join '|') -match 'Excluded|Generated|AutoGenerated') { throw 'An excluded enum, delegate, or generated declaration was enumerated.' }
    if (@($enumeration.candidates | Where-Object { $_.symbol -match 'Repeated' }).Count -ne 2) { throw 'Partial declarations were not preserved with disambiguators.' }
    if (@($enumeration.candidates | Where-Object change -eq 'Unknown').Count -ne 1) { throw 'Unchanged declarations outside the changed document were not kept explicitly unknown.' }
    Write-Output 'M0015 focused fixtures passed: candidate eligibility, nested types, partial disambiguation, exclusions, history, calibration fallback, budgets, and determinism.'
    return
}

if ($Action -eq 'integrity') {
    $frozen = Get-Content (Join-Path $repoRoot 'tools/M0015/FrozenGateEvidence.json') -Raw | ConvertFrom-Json
    foreach ($gate in $frozen.gates) {
        $headPath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-head-candidates.json"
        $basePath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-base-candidates.json"
        $resultPath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-comparison.json"
        $head = Get-Content $headPath -Raw | ConvertFrom-Json
        $base = Get-Content $basePath -Raw | ConvertFrom-Json
        $result = Get-Content $resultPath -Raw | ConvertFrom-Json
        if ($head.candidateCount -ne $gate.headCandidateCount -or $base.candidateCount -ne $gate.baseCandidateCount) { throw "Candidate count does not match frozen manifest for $($gate.id)." }
        if ($result.base -ne $gate.base -or $result.head -ne $gate.head -or $result.seed -ne $gate.seed -or $result.budget -ne 5) { throw "Gate identity/protocol mismatch for $($gate.id)." }
        $eligible = @{}; foreach ($candidate in $head.candidates) { $eligible[$candidate.id] = $true }
        foreach ($policy in @('uniform', 'change-first', 'history-aware')) {
            $items = @($result.policies.$policy.selected)
            if ($items.Count -ne [Math]::Min(5, $result.population.comparisonPool)) { throw "Selection budget violation for $($gate.id)/$policy." }
            if (@($items.id | Sort-Object -Unique).Count -ne $items.Count) { throw "Duplicate selection in $($gate.id)/$policy." }
            foreach ($item in $items) { if (-not $eligible.ContainsKey($item.id)) { throw "Selected identity is not eligible at head for $($gate.id)/$policy." } }
        }
    }
    $hashFiles = @(
        (Join-Path $repoRoot 'tools/M0015/FrozenGateEvidence.json'),
        (Join-Path $repoRoot 'tools/M0015/Gates.json'),
        (Join-Path $repoRoot 'tools/M0015/reviewer-sample.json'),
        (Join-Path $repoRoot 'docs/research/GATE-LOCAL-SAMPLING-PROTOTYPE.md')
    ) + @(Get-ChildItem (Join-Path $repoRoot 'tools/M0015/results') -Filter '*.json' | ForEach-Object FullName)
    $lines = foreach ($path in $hashFiles | Sort-Object) { $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash; "$hash  $([IO.Path]::GetRelativePath($repoRoot, $path).Replace('\', '/'))" }
    [IO.File]::WriteAllLines((Join-Path $repoRoot 'tools/M0015/results/SHA256SUMS.txt'), [string[]]$lines)
    Write-Output "Integrity passed: gate revisions/seeds/budgets, candidate counts, selected identity membership/uniqueness, and SHA-256 manifest for $($frozen.gates.Count) gates plus protocol, report and blinded sample."
    return
}

if ([string]::IsNullOrWhiteSpace($SecondRepositoryPath)) { throw 'Pass -SecondRepositoryPath with a clone of carlrabbit/dotnet-semantic-type-model.' }
$SecondRepositoryPath = (Resolve-Path $SecondRepositoryPath).Path
if ([string]::IsNullOrWhiteSpace($EvidenceRoot)) { $EvidenceRoot = Join-Path $env:TEMP 'M0015-gate-evidence' }
$EvidenceRoot = [IO.Path]::GetFullPath($EvidenceRoot)
New-Item -ItemType Directory -Path $EvidenceRoot -Force | Out-Null
$settings = Get-Content $configuration -Raw | ConvertFrom-Json
$gates = $settings.gates
$resultRoot = Join-Path $repoRoot 'tools/M0015/results'
New-Item -ItemType Directory -Path $resultRoot -Force | Out-Null
$prepared = @()

foreach ($gate in $gates) {
    $source = if ($gate.id -eq 'hygiene-pr15') { $repoRoot } else { $SecondRepositoryPath }
    foreach ($revision in @($gate.base, $gate.head)) {
        $actual = (& git -C $source rev-parse $revision).Trim()
        if ($LASTEXITCODE -ne 0 -or $actual -ne $revision) { throw "Frozen revision $revision is unavailable in $source." }
    }
    $gateRoot = Join-Path $EvidenceRoot $gate.id
    $baseWorktree = Join-Path $gateRoot 'base'
    $headWorktree = Join-Path $gateRoot 'head'
    New-Item -ItemType Directory -Path $gateRoot -Force | Out-Null
    foreach ($entry in @(@{Path=$baseWorktree;Ref=$gate.base}, @{Path=$headWorktree;Ref=$gate.head})) {
        if (-not (Test-Path $entry.Path)) {
            & git -C $source worktree add --detach $entry.Path $entry.Ref
            if ($LASTEXITCODE -ne 0) { throw "Could not materialize frozen worktree $($entry.Ref)." }
        }
        $worktreeHead = (& git -C $entry.Path rev-parse HEAD).Trim()
        if ($LASTEXITCODE -ne 0 -or $worktreeHead -ne $entry.Ref) { throw "Existing worktree is not at frozen revision $($entry.Ref): $($entry.Path)." }
        $dirty = & git -C $entry.Path status --porcelain --untracked-files=all
        if ($LASTEXITCODE -ne 0 -or @($dirty).Count -gt 0) { throw "Existing frozen worktree is dirty: $($entry.Path)." }
    }
    $changed = Join-Path $gateRoot 'changed-paths.txt'
    $changedOutput = & git -C $source diff --name-only --diff-filter=ACDMRT $gate.base $gate.head
    if ($LASTEXITCODE -ne 0) { throw "Could not read frozen gate diff for $($gate.id)." }
    [IO.File]::WriteAllLines($changed, [string[]]$changedOutput)
    $baseChanged = Join-Path $gateRoot 'base-changed-paths.txt'
    [IO.File]::WriteAllText($baseChanged, '')
    $baseCandidates = Join-Path $resultRoot "$($gate.id)-base-candidates.json"
    $headCandidates = Join-Path $resultRoot "$($gate.id)-head-candidates.json"
    $gateConfig = Join-Path $gateRoot 'gate.json'
    $seed = $settings.seeds.PSObject.Properties[$gate.id].Value
    $canonicalDiff = (@($changedOutput | Sort-Object) -join "`n")
    if ($canonicalDiff.Length -gt 0) { $canonicalDiff += "`n" }
    $diffHash = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($canonicalDiff)))
    $enumerationTimes = @{}
    foreach ($spec in @(@{Root=$baseWorktree;Changed=$baseChanged;Out=$baseCandidates}, @{Root=$headWorktree;Changed=$changed;Out=$headCandidates})) {
        $solution = Join-Path $spec.Root $gate.solution
        if (-not (Test-Path $solution)) { throw "Frozen solution $($gate.solution) is absent at $($gate.id) snapshot." }
        $timer = [Diagnostics.Stopwatch]::StartNew()
        $json = & dotnet $toolDll enumerate $spec.Root $solution $spec.Changed
        $timer.Stop()
        if ($LASTEXITCODE -ne 0) { throw "Roslyn enumeration failed for $($gate.id)." }
        [IO.File]::WriteAllText($spec.Out, ($json -join [Environment]::NewLine) + [Environment]::NewLine)
        $enumerationTimes[$spec.Out] = [Math]::Round($timer.Elapsed.TotalMilliseconds, 3)
    }
    $gateRecord = [ordered]@{ id=$gate.id; repository=$gate.repository; base=$gate.base; head=$gate.head; seed=$seed; budget=5; unchangedCohortMaximum=25; changedPathCount=@($changedOutput).Count; changedPathSha256=$diffHash; baseEnumerationMs=$enumerationTimes[$baseCandidates]; headEnumerationMs=$enumerationTimes[$headCandidates] }
    [IO.File]::WriteAllText($gateConfig, ($gateRecord | ConvertTo-Json))
    $prepared += [pscustomobject]@{ Gate=$gate; GateConfig=$gateConfig; BaseCandidates=$baseCandidates; HeadCandidates=$headCandidates; Result=(Join-Path $resultRoot "$($gate.id)-comparison.json"); DiffPath=$changed; DiffHash=$diffHash; ChangedCount=@($changedOutput).Count; ChangedPaths=@($changedOutput); BaseTime=$enumerationTimes[$baseCandidates]; HeadTime=$enumerationTimes[$headCandidates] }
}

$machine = Get-CimInstance Win32_OperatingSystem
$frozenEvidence = [ordered]@{
    schemaVersion = 1
    frozenBeforeFinalComparison = $true
    environment = [ordered]@{ os=$machine.Caption; osVersion=$machine.Version; platform=[Runtime.InteropServices.RuntimeInformation]::OSDescription; dotnetSdk=((& dotnet --version).Trim()); powershell=$PSVersionTable.PSVersion.ToString(); git=((& git --version).Trim()); processorCount=[Environment]::ProcessorCount }
    protocol = [ordered]@{ rule='architecture.boringness.review@2'; budget=5; unchangedCohortMaximum=25; policies=@('uniform','change-first','history-aware'); pairedRandomness='same seed-derived per-candidate variate across policies'; calibrationGridVersion='m0015-grid-v1'; seedVersion='m0015-v1' }
    gates = @($prepared | ForEach-Object {
        $baseData = Get-Content $_.BaseCandidates -Raw | ConvertFrom-Json
        $headData = Get-Content $_.HeadCandidates -Raw | ConvertFrom-Json
        [ordered]@{ id=$_.Gate.id; repository=$_.Gate.repository; base=$_.Gate.base; head=$_.Gate.head; seed=$settings.seeds.PSObject.Properties[$_.Gate.id].Value; changedPathCount=$_.ChangedCount; changedPathSha256=$_.DiffHash; changedPaths=$_.ChangedPaths; baseCandidateCount=$baseData.candidateCount; headCandidateCount=$headData.candidateCount; baseWorkspaceDiagnosticCount=@($baseData.workspaceDiagnostics).Count; headWorkspaceDiagnosticCount=@($headData.workspaceDiagnostics).Count; baseEnumerationMs=$_.BaseTime; headEnumerationMs=$_.HeadTime }
    })
}
$frozenPath = Join-Path $repoRoot 'tools/M0015/FrozenGateEvidence.json'
[IO.File]::WriteAllText($frozenPath, ($frozenEvidence | ConvertTo-Json -Depth 8) + [Environment]::NewLine)

foreach ($entry in $prepared) {
    Invoke-Checked 'dotnet' @($toolDll, 'compare', $entry.BaseCandidates, $entry.HeadCandidates, $entry.GateConfig, $entry.Result) "M0015 comparison for $($entry.Gate.id)"
}
Write-Output "M0015 gate replay outputs: $resultRoot; local worktrees: $EvidenceRoot"
