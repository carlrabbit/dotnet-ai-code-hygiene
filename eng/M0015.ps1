function Invoke-Checked([string]$File, [string[]]$Arguments, [string]$Description) {
    & $File @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$Description failed with exit code $LASTEXITCODE." }
}

function Get-IntegrityPaths([string]$Root) {
    $paths = @(Get-ChildItem (Join-Path $Root 'tools/M0015') -File -Recurse | Where-Object {
        $_.FullName -notmatch '[\\/]bin[\\/]|[\\/]obj[\\/]' -and $_.Name -ne 'SHA256SUMS.txt'
    } | ForEach-Object { [IO.Path]::GetRelativePath($Root, $_.FullName).Replace('\', '/') })
    $paths += @('eng/M0015.ps1', 'docs/research/GATE-LOCAL-SAMPLING-PROTOTYPE.md', 'docs/milestones/M0015-gate-local-sampling-prototype.md', '.execution/M0015-gate-local-sampling-prototype.md', '.review/REV-M0015-COMPLETION.md')
    return @($paths | Sort-Object -Unique)
}

function Test-ChecksumManifest([string]$Root, [string]$ManifestPath, [string[]]$ExpectedPaths) {
    if (-not (Test-Path -LiteralPath $ManifestPath)) { throw "Checksum reference is missing: $ManifestPath" }
    $entries = @{}
    foreach ($line in [IO.File]::ReadAllLines($ManifestPath)) {
        if ($line -notmatch '^([A-Fa-f0-9]{64})  (.+)$') { throw "Malformed checksum reference line: $line" }
        $relative = $Matches[2].Replace('\', '/')
        if ($entries.ContainsKey($relative)) { throw "Duplicate checksum reference: $relative" }
        $entries[$relative] = $Matches[1].ToUpperInvariant()
    }
    $expectedSet = @{}; foreach ($path in $ExpectedPaths) { $expectedSet[$path] = $true }
    $actualPaths = @($entries.Keys | Sort-Object)
    $expectedOrdered = @($ExpectedPaths | Sort-Object -Unique)
    $missing = @($expectedOrdered | Where-Object { -not $entries.ContainsKey($_) })
    $unexpected = @($actualPaths | Where-Object { -not $expectedSet.ContainsKey($_) })
    if ($missing.Count -gt 0 -or $unexpected.Count -gt 0) { throw "Checksum inventory mismatch. Missing: $($missing -join ', '); unexpected: $($unexpected -join ', ')." }
    foreach ($relative in $expectedOrdered) {
        $path = Join-Path $Root ($relative.Replace('/', [IO.Path]::DirectorySeparatorChar))
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Required integrity artifact is missing: $relative" }
        $actual = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToUpperInvariant()
        if ($actual -ne $entries[$relative]) { throw "Checksum mismatch: $relative" }
    }
}

function Write-ChecksumManifest([string]$Root, [string]$ManifestPath, [string[]]$ExpectedPaths) {
    $lines = foreach ($relative in ($ExpectedPaths | Sort-Object -Unique)) {
        $path = Join-Path $Root ($relative.Replace('/', [IO.Path]::DirectorySeparatorChar))
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Required integrity artifact is missing: $relative" }
        $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
        "$hash  $relative"
    }
    [IO.File]::WriteAllLines($ManifestPath, [string[]]$lines)
}

