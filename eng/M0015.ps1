if ($Action -in @('integrity', 'regenerate-integrity')) {
    $frozen = Get-Content (Join-Path $repoRoot 'tools/M0015/FrozenGateEvidence.json') -Raw | ConvertFrom-Json
    foreach ($gate in $frozen.gates) {
        $headPath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-head-candidates.json"
        $basePath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-base-candidates.json"
        $resultPath = Join-Path $repoRoot "tools/M0015/results/$($gate.id)-comparison.json"
        $head = Get-Content $headPath -Raw | ConvertFrom-Json
        $base = Get-Content $basePath -Raw | ConvertFrom-Json
        $result = Get-Content $resultPath -Raw | ConvertFrom-Json
        if ($head.candidateCount -ne $gate.headCandidateCount -or $base.candidateCount -ne $gate.baseCandidateCount) { throw "Candidate count does not match frozen manifest for $($gate.id)." }
        if ($result.base -ne $gate.base -or $result.head -ne $gate.head -or $result.seed -ne $gate.seed -or $result.budget -ne 5) { throw "Gate identity/protocol mismatch for $($gate.id)." }
        $eligible = @{}; foreach ($candidate in $head.candidates) { $eligible[$candidate.id] = $true }
        foreach ($policy in @('uniform', 'change-first', 'history-aware')) {
            $items = @($result.policies.$policy.selected)
            if ($items.Count -ne [Math]::Min(5, $result.population.comparisonPool)) { throw "Selection budget violation for $($gate.id)/$policy." }
            if (@($items.id | Sort-Object -Unique).Count -ne $items.Count) { throw "Duplicate selection in $($gate.id)/$policy." }
            foreach ($item in $items) { if (-not $eligible.ContainsKey($item.id)) { throw "Selected identity is not eligible at head for $($gate.id)/$policy." } }
        }
        $changeFirstIds = @($result.policies.'change-first'.selected | Where-Object change -eq 'NewOrChanged' | ForEach-Object id)
        $historyIds = @($result.policies.'history-aware'.selected | Where-Object change -eq 'NewOrChanged' | ForEach-Object id)
        $omitted = @($changeFirstIds | Where-Object { $_ -notin $historyIds })
        $countDifference = $changeFirstIds.Count - $historyIds.Count
        if ($result.displacement.changedSelectionCountDifference -ne $countDifference -or $result.displacement.changedCandidateIdentityDisplacementCount -ne $omitted.Count) { throw "Changed-count or candidate-identity displacement mismatch for $($gate.id)." }
        $changeAll = @($result.policies.'change-first'.selected.id)
        $historyAll = @($result.policies.'history-aware'.selected.id)
        $symmetricDifference = @($changeAll | Where-Object { $_ -notin $historyAll }).Count + @($historyAll | Where-Object { $_ -notin $changeAll }).Count
        if ($result.displacement.selectedIdentitySymmetricDifferenceCount -ne $symmetricDifference) { throw "Selected identity symmetric-difference mismatch for $($gate.id)." }
        $omittedSet = @($result.displacement.changeFirstChangedCandidatesOmittedByHistoryAware | ForEach-Object id | Sort-Object)
        if (($omittedSet -join '|') -ne (@($omitted | Sort-Object) -join '|')) { throw "Reported omitted changed identities do not match selected identities for $($gate.id)." }
        if (@($result.displacement.historyAwareReplacementCandidates).Count -ne @($historyAll | Where-Object { $_ -notin $changeAll }).Count) { throw "Replacement candidate count mismatch for $($gate.id)." }
    }
    $expectedPaths = Get-IntegrityPaths $repoRoot
    $manifestPath = Join-Path $repoRoot 'tools/M0015/results/SHA256SUMS.txt'
    if ($Action -eq 'regenerate-integrity') {
        Write-ChecksumManifest $repoRoot $manifestPath $expectedPaths
        Write-Output "Regenerated checksum reference for $($expectedPaths.Count) required artifacts. Run -Action integrity to verify read-only."
    } else {
        Test-ChecksumManifest $repoRoot $manifestPath $expectedPaths
        Write-Output "Integrity passed read-only: gate revisions/seeds/budgets, candidate counts, selection identity membership/uniqueness, and $($expectedPaths.Count) checksummed artifacts across $($frozen.gates.Count) gates."
    }
    return
}

